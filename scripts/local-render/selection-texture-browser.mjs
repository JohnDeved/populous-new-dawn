import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

export const selectionTextureLimitMs = 18000
const imagePath = '/original/selection.png'
const expectedImageSha256 = '06973642cc385da1de1b7195cb25781c108dc4fd0c9baa23f95833185ed54348'
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex')

// This controlled case samples the existing selected clone without assigning
// texture image, movement, render visibility, World state, or view fields.
export function readSelectionTextureOwner() {
  const scene = window.testSceneRef.current, world = window.testStore.getWorld(), id = 30,
    canvas = scene.renderer.domElement, group = scene.unitMeshes.get(id),
    sprite = group?.userData.selection, map = sprite?.material.map
  if (!sprite || !map) throw Error('Selected Shaman must already own her cloned selection sprite')
  const snapshot = () => {
    const u = world.units.find(unit => unit.id === id), rect = canvas.getBoundingClientRect(),
      position = scene.unitScreen(id), image = map.image
    if (window.testSceneRef.current !== scene || window.testStore.getWorld() !== world ||
      scene.world !== world || !canvas.isConnected || world.outcome.level !== 1 ||
      world.status !== 'playing' || world.inputMask || !world.paused || scene.messageModal ||
      scene.cameraMotion.active || scene.viewTransition || !u || u.hp <= 0 || u.team !== 'blue' ||
      u.kind !== 'shaman' || scene.unitMeshes.get(id) !== group ||
      group.userData.selection !== sprite || sprite.material.map !== map ||
      !group.visible || !sprite.isSprite || !position ||
      !Number.isInteger(group.userData.frame) || group.userData.frame < 0)
      throw Error('Selection texture lost the same paused authored Shaman and sprite')
    const x = rect.left + (position.x + 1) * rect.width / 2,
      y = rect.top + (1 - position.y) * rect.height / 2
    if (Math.abs(position.x) >= 1 || Math.abs(position.y) >= 1 || document.elementFromPoint(x, y) !== canvas)
      throw Error('Selected Shaman must be genuinely visible on canvas')
    return { turn: world.turn, selected: [...world.selected], actor: { id, x: u.x, z: u.z, pose: group.userData.frame },
      camera: { ...scene.cameraPosition }, anchor: { x, y }, frame: scene.renderer.info.render.frame,
      visible: sprite.visible, submitted: !!scene.view.painter.source(sprite),
      image: image ? { url: image.currentSrc || image.src, complete: image.complete,
        width: image.naturalWidth, height: image.naturalHeight } : null,
      size: [sprite.scale.x, sprite.scale.y] }
  }
  return { snapshot }
}

// Only this independent browser context gets a cold cache and delayed image.
// Release is the original HTTP request, never fulfill with generated bytes.
export async function checkSelectionTexture({ browser, url, output, signal, enterMission, closeContext, outerReceipt }) {
  const start = performance.now(), deadline = start + selectionTextureLimitMs,
    imageUrl = new URL(imagePath, url).href
  const report = { status: 'running', limitMs: selectionTextureLimitMs, imagePath, requests: [], captures: [],
    scope: 'Existing public M1 with one delayed authentic static texture; not a general network or alpha-behavior test.' }
  const save = () => writeFileSync(resolve(output, 'selection-texture.json'), JSON.stringify(report, null, 2) + '\n')
  const remaining = cap => {
    signal.throwIfAborted()
    const left = Math.floor(deadline - performance.now())
    assert.ok(left > 0 && !timedOut, 'Selection image episode exceeded its fixed deadline')
    return Math.min(cap, left)
  }
  let context, page, observer, timer, installed = false, timedOut = false, failed = false, failure, primaryRequest
  const deliveries = [], cleanupErrors = []
  let release
  const gate = new Promise(resolve => { release = resolve })
  const handler = route => {
    const request = route.request()
    primaryRequest ??= request
    report.requests.push({ url: request.url(), method: request.method(), type: request.resourceType() })
    const delivery = gate.then(() => route.continue())
    deliveries.push(delivery)
    // Retain each result for strict teardown reporting, not as an unhandled rejection.
    return delivery.catch(() => {})
  }
  const see = () => observer.evaluate(h => h.snapshot())
  const wait = async (fn, args, cap) => {
    const h = await page.waitForFunction(fn, { ...args, observer }, { timeout: remaining(cap) })
    try { return await h.jsonValue() } finally { await h.dispose() }
  }
  const capture = async (name, condition) => {
    const before = await see()
    assert.ok(condition(before), `Missing required selection state before ${name}`)
    const png = await page.screenshot({ path: resolve(output, name), timeout: remaining(2500) })
    const after = await see()
    assert.ok(condition(after), `Selection owner changed during ${name}`)
    assert.deepEqual([after.turn, after.actor, after.selected, after.camera],
      [before.turn, before.actor, before.selected, before.camera])
    report.captures.push({ name, sha256: sha256(png), before, after })
    return after
  }
  save()
  try {
    context = await browser.newContext({ viewport: { width: 800, height: 600 }, deviceScaleFactor: 1 })
    timer = setTimeout(() => { timedOut = true; release(); void context.close().catch(() => {}) }, remaining(selectionTextureLimitMs))
    page = await context.newPage()
    page.setDefaultTimeout(remaining(6500))
    await page.route(imageUrl, handler)
    installed = true
    await page.goto(url, { waitUntil: 'domcontentloaded', timeout: remaining(6500) })
    await enterMission(page)
    await page.getByRole('button', { name: 'Pause game', exact: true }).click({ timeout: remaining(2200) })
    assert.deepEqual(report.requests, [{ url: imageUrl, method: 'GET', type: 'image' }])
    assert.ok(primaryRequest)
    observer = await page.evaluateHandle(readSelectionTextureOwner)
    const initial = await see()
    assert.deepEqual(initial.selected, [30])
    await wait(({ observer, frame }) => observer.snapshot().frame > frame, { frame: initial.frame }, 2500)
    const before = await capture('selection-texture-pending.png', row =>
      !row.image && !row.visible && !row.submitted && JSON.stringify(row.selected) === '[30]')
    const responseWaiting = page.waitForResponse(
      response => response.url() === imageUrl && response.request() === primaryRequest,
      { timeout: remaining(4600) }
    )
    release()
    const response = await responseWaiting
    assert.equal(response.status(), 200)
    assert.match(response.headers()['content-type'] ?? '', /^image\/png(?:\s*;|$)/i)
    const byteSha256 = sha256(await response.body())
    assert.equal(byteSha256, expectedImageSha256)
    report.response = { url: response.url(), status: response.status(), sha256: byteSha256 }
    const ready = await wait(({ observer, imageUrl, frame }) => {
      const row = observer.snapshot()
      return row.frame > frame && row.image?.complete === true && row.image.url === imageUrl &&
        row.image.width === 9 && row.image.height === 7 && row.visible && row.submitted && row
    }, { imageUrl, frame: before.frame }, 3200)
    const after = await capture('selection-texture-released.png', row =>
      row.image?.url === imageUrl && row.image.complete && row.visible && row.submitted && row.frame >= ready.frame)
    assert.deepEqual([after.turn, after.actor, after.selected, after.camera, after.anchor],
      [before.turn, before.actor, before.selected, before.camera, before.anchor])
    assert.ok(after.size[0] > 0 && after.size[1] > 0 && after.frame > before.frame)
    assert.notEqual(report.captures[0].sha256, report.captures[1].sha256)
  } catch (error) { failed = true; failure = error }
  finally {
    release()
    const attempt = async fn => { try { await fn() } catch (error) { cleanupErrors.push(String(error)); if (!failed) { failed = true; failure = error } } }
    if (observer) await attempt(() => observer.dispose())
    if (installed) {
      // Keep the context live until the existing route settles, remove just our
      // handler, then drain any arrival that raced the removal.
      const drain = async offset => {
        const settled = await Promise.allSettled(deliveries.slice(offset))
        for (const delivery of settled) if (delivery.status === 'rejected') throw delivery.reason
      }
      const started = deliveries.length
      await attempt(() => drain(0))
      if (!page.isClosed()) await attempt(() => page.unroute(imageUrl, handler))
      await attempt(() => drain(started))
      if (!failed) await attempt(async () => assert.equal(report.requests.length, 1))
    }
    if (context) await attempt(() => closeContext(context, failed, outerReceipt))
    clearTimeout(timer)
    if (!failed) await attempt(async () => remaining(selectionTextureLimitMs))
    if (failed) report.error = String(failure)
    if (cleanupErrors.length) report.cleanupErrors = cleanupErrors
    report.elapsedMs = performance.now() - start
    report.status = failed ? 'failed' : 'passed'
    save()
  }
  if (failed) throw failure
  return report
}
