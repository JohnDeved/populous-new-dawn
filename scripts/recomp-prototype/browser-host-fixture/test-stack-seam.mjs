import assert from 'node:assert/strict';
import {makeModule} from './stack-seam.mjs';
const module=makeModule();
assert.equal(typeof WebAssembly.Suspending,'function');
assert.equal(typeof WebAssembly.promising,'function');
let resolveWait,seen;
const instance=new WebAssembly.Instance(module,{env:{wait:new WebAssembly.Suspending(x=>{seen=x;return new Promise(r=>{resolveWait=r;});})}});
const call=WebAssembly.promising(instance.exports.run);
let settled=false;
const pending=call(5).then(x=>{settled=true;return x;});
assert.equal(seen,5);assert.equal(settled,false);
let tick=false;await new Promise(r=>setTimeout(()=>{tick=true;r();},5));
assert.equal(tick,true);assert.equal(settled,false);
resolveWait(6);assert.equal(await pending,25);
const error=Error('synthetic rejection');
const rejectInstance=new WebAssembly.Instance(module,{env:{wait:new WebAssembly.Suspending(()=>Promise.reject(error))}});
await assert.rejects(WebAssembly.promising(rejectInstance.exports.run)(1),e=>e===error);
const sync=new WebAssembly.Instance(module,{env:{wait:x=>x+1}});
assert.equal(sync.exports.run(5),25);
console.log(JSON.stringify({scope:'Node JSPI, synthetic nested WASM calls; not compiled C or browser proof',cases:['synchronous baseline','nested stack preserved across pending Promise','event loop remains responsive','rejection identity retained'],passed:4,memory:process.memoryUsage()},null,2));
