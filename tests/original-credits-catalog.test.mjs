test('identical repeated heading references are accepted without changing records', () => {
  const record = { headingId: 1073, text: 'Stuart Whyte' }
  const headings = [
    { languageId: 1073, text: 'Producer' },
    { languageId: 1073, text: 'Producer' },
  ]
  assert.deepEqual(resolveCreditsHeadings([record], headings), {
    headings: { 1073: 'Producer' },
    records: [record],
  })
})

test('missing or conflicting heading resolution fails rather than inventing a label', () => {
  assert.throws(
    () => resolveCreditsHeadings([{ headingId: 1073, text: 'name' }], []),
    /Missing heading 1073/
  )
  assert.throws(
    () =>
      resolveCreditsHeadings(
        [],
        [
          { languageId: 1073, text: 'Producer' },
          { languageId: 1073, text: 'Different' },
        ]
      ),
    /Conflicting heading 1073/
  )
  assert.throws(
    () => resolveCreditsHeadings([], [{ languageId: 1073, text: '' }]),
    /Missing heading label/
  )
})

test('zero is no heading after parsing, not the original digit-zero heading', () => {
  assert.deepEqual(resolveCreditsHeadings([{ headingId: 0, text: null }], []), {
    headings: {},
    records: [{ headingId: 0, text: null }],
  })
  assert.throws(
    () => resolveCreditsHeadings([{ headingId: 1071, text: '  ' }], []),
    /Missing heading 1071/
  )
})

test('malformed record and language IDs fail closed', () => {
  for (const headingId of [-1, 65536, 1.5, '1071', NaN])
    assert.throws(
      () => resolveCreditsHeadings([{ headingId, text: null }], []),
      /Invalid record heading ID/
    )
  for (const languageId of [0, -1, 65536, 1.5, '1071', NaN])
    assert.throws(
      () => resolveCreditsHeadings([], [{ languageId, text: 'label' }]),
      /Invalid heading ID/
    )
  assert.throws(
    () => resolveCreditsHeadings([{ headingId: 0, text: undefined }], []),
    /Invalid record text/
  )
})

for (const corrupt of ['inventory', 'parser']) {
  test(`changed ${corrupt} identity is rejected before catalogue generation`, async () => {
    const scratch = mkdtempSync(resolve(tmpdir(), 'pnd-credits-catalog-'))
    try {
      for (const field of ['inventory', 'parser']) {
        const path = resolve(scratch, CREDITS_SOURCE[field])
        mkdirSync(dirname(path), { recursive: true })
        const original = readFileSync(resolve(root, CREDITS_SOURCE[field]))
        writeFileSync(
          path,
          field === corrupt ? Buffer.concat([original, Buffer.from('\n')]) : original
        )
      }
      await assert.rejects(
        buildOriginalCredits(scratch),
        corrupt === 'inventory' ? /Inventory identity changed/ : /Parser identity changed/
      )
    } finally {
      rmSync(scratch, { recursive: true, force: true })
    }
  })
}
