import test from 'node:test'
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { readFileSync, mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  buildOriginalCredits,
  CREDITS_SOURCE,
  resolveCreditsHeadings,
  serializeCreditsCatalog,
} from '../scripts/build-original-credits.mjs'

const root = fileURLToPath(new URL('../', import.meta.url))
const hash = data => createHash('sha256').update(data).digest('hex')
const expectedOutput = '097b89ed0d4cd2b0f0f66808db8f59af2df69bd64447e5e1bdc11e4f353d65e0'

test('inactive catalogue reproduces every pinned source record and exact generated bytes', async () => {
  const catalog = await buildOriginalCredits()
  const serialized = serializeCreditsCatalog(catalog)
  assert.equal(serialized, readFileSync(resolve(root, 'app/original-credits.json'), 'utf8'))
  assert.equal(hash(serialized), expectedOutput)
  assert.equal(hash(JSON.stringify(catalog.records)), CREDITS_SOURCE.recordsSha256)
  assert.equal(catalog.records.length, 280)
  assert.equal(catalog.records.filter(record => record.headingId).length, 101)
  assert.equal(Object.keys(catalog.headings).length, 100)
  assert.equal(
    catalog.records.filter(record => record.text !== null && /^ +$/.test(record.text)).length,
    50
  )
  assert.deepEqual(catalog.records.at(-1), { headingId: 0, text: null })
  assert.equal(catalog.headings[1071], 'Production')
  assert.equal(catalog.headings[1178], 'Thanks To')
  assert.deepEqual(
    catalog.records.filter(record => record.headingId === 1073).map(record => record.text),
    ['Stuart Whyte', 'Dan Blackstone']
  )
  assert.ok(catalog.records.some(record => record.text === 'Michael Willis '))
  assert.ok(catalog.records.some(record => record.text === 'James Lenoël, Oli Ladenburg'))
})

