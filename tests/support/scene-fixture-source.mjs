// Optional, explicit offline output for the existing Node scene fixture only.
// This is not a general transpiler/cache. No application source is evaluated here.
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { closeSync, fstatSync, lstatSync, openSync, readSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, isAbsolute, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
let ts
const hash = bytes => createHash('sha256').update(bytes).digest('hex')
const digest = value => typeof value === 'string' && /^[a-f0-9]{64}$/.test(value)
const sourceName = name => typeof name === 'string' && /^[a-z0-9-]+\.ts$/.test(name)

export function sceneFixtureSource(source) {
  // The level importer emits a JavaScript data literal, even though its output
  // has a .ts suffix. Do not parse/type-check/print those large tables again.
  // The source-contract test checks every generator-owned level, including its
  // complete literal shape and equality with the unchanged compiler output.
  if (/^\/\/ Generated by scripts\/import-level\.py from the supplied levl\d+\.dat\.\r?\nexport default \{/.test(source))
    return source
  ts ??= require('typescript')
  return ts.transpileModule(source, {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
  }).outputText
}

// Hash tool/source bytes without retaining a compiler-sized Buffer or importing it.
export function sceneFixtureFileHash(path) {
  const fd = openSync(path, 'r')
  try {
    assert(fstatSync(fd).isFile(), 'Fixture identity must name a regular file')
    const buffer = Buffer.allocUnsafe(64 * 1024), result = createHash('sha256')
    let count
    while ((count = readSync(fd, buffer, 0, buffer.length, null)))
      result.update(buffer.subarray(0, count))
    return result.digest('hex')
  } finally {
    closeSync(fd)
  }
}

export function sceneFixtureIdentity() {
  const packagePath = require.resolve('typescript/package.json')
  return {
    node: process.versions.node,
    platform: process.platform,
    arch: process.arch,
    typescript: JSON.parse(sceneFixtureReadBounded(packagePath, 256 * 1024)).version,
    compilerSha256: sceneFixtureFileHash(require.resolve('typescript')),
    compilerPackageSha256: sceneFixtureFileHash(packagePath),
    transformerSha256: sceneFixtureFileHash(fileURLToPath(import.meta.url)),
    hookSha256: sceneFixtureFileHash(new URL('./bloodlust-scene.mjs', import.meta.url)),
    preparerSha256: sceneFixtureFileHash(new URL('../../scripts/prepare-scene-fixture.mjs', import.meta.url)),
    options: { target: 'ES2022', module: 'ESNext' },
  }
}

export function sceneFixtureReadBounded(path, limit) {
  assert(lstatSync(path).isFile(), 'Fixture output must be a real file')
  const fd = openSync(path, 'r')
  try {
    const stat = fstatSync(fd)
    assert(stat.isFile() && stat.size <= limit, 'Invalid/oversized fixture output')
    const bytes = Buffer.allocUnsafe(stat.size)
    let offset = 0
    while (offset < bytes.length) {
      const count = readSync(fd, bytes, offset, bytes.length - offset, null)
      assert(count > 0, 'Fixture output shrank during read')
      offset += count
    }
    assert.equal(readSync(fd, Buffer.allocUnsafe(1), 0, 1, null), 0, 'Fixture output grew during read')
    assert.equal(fstatSync(fd).size, stat.size, 'Fixture output changed during read')
    return bytes
  } finally {
    closeSync(fd)
  }
}

export function sceneFixtureSourceForApp(app) {
  const path = process.env.PND_SCENE_FIXTURE_PRECOMPILED
  const expected = process.env.PND_SCENE_FIXTURE_PRECOMPILED_SHA256
  if (path === undefined && expected === undefined)
    return (_url, source) => sceneFixtureSource(source)
  assert(path && isAbsolute(path) && digest(expected), 'Both pinned fixture-output settings are required')
  const bytes = sceneFixtureReadBounded(path, 256 * 1024)
  assert.equal(hash(bytes), expected, 'Fixture manifest hash mismatch')
  const manifest = JSON.parse(bytes)
  assert.equal(manifest.format, 'scene-fixture-output-v1')
  assert(/^[a-f0-9]{40}$/.test(manifest.sourceCommit) && digest(manifest.requestSha256))
  assert.deepEqual(manifest.identity, sceneFixtureIdentity(), 'Fixture compiler/source/runtime identity mismatch')
  assert(Array.isArray(manifest.entries) && manifest.entries.length > 0 && manifest.entries.length <= 512)
  const entries = new Map()
  for (const entry of manifest.entries) {
    assert(sourceName(entry.name) && !entries.has(entry.name), 'Invalid/duplicate fixture source')
    assert(digest(entry.sourceSha256) && digest(entry.outputSha256), 'Invalid fixture entry hashes')
    assert(Number.isSafeInteger(entry.sourceBytes) && entry.sourceBytes >= 0 && entry.sourceBytes <= 256 * 1024)
    assert(Number.isSafeInteger(entry.outputBytes) && entry.outputBytes >= 0 && entry.outputBytes <= 512 * 1024)
    entries.set(entry.name, entry)
  }
  const modules = join(dirname(path), 'modules')
  assert(lstatSync(modules).isDirectory(), 'Fixture modules must be a real directory')
  return (url, source) => {
    assert(url.startsWith(app.href), 'Foreign URL outside fixture output scope')
    const name = url.slice(app.href.length), entry = entries.get(name)
    assert(entry, `No precompiled fixture output for ${name}`)
    assert.equal(Buffer.byteLength(source), entry.sourceBytes, `Stale fixture source: ${name}`)
    assert.equal(hash(source), entry.sourceSha256, `Stale fixture source: ${name}`)
    const output = sceneFixtureReadBounded(join(modules, `${name}.mjs`), 512 * 1024)
    assert.equal(output.length, entry.outputBytes, `Invalid fixture output length: ${name}`)
    assert.equal(hash(output), entry.outputSha256, `Invalid fixture output hash: ${name}`)
    return output.toString('utf8')
  }
}
