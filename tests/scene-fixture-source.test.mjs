import assert from 'node:assert/strict'
import { readFileSync, readdirSync } from 'node:fs'
import test from 'node:test'
import ts from 'typescript'
import { sceneFixtureSource } from './support/bloodlust-scene.mjs'

const root = new URL('../', import.meta.url)
const previous = source => ts.transpileModule(source, {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
}).outputText
const evaluate = async source => (await import(
  `data:text/javascript;base64,${Buffer.from(source).toString('base64')}`
)).default

// This is deliberately a data contract, not a second TypeScript transpiler.
// Reject imports, calls, identifiers-as-values, getters, computed properties,
// spreads, class fields and TypeScript syntax in the compiler-bypassed sources.
function assertDataLiteral(node, file) {
  if (ts.isObjectLiteralExpression(node)) {
    for (const property of node.properties) {
      assert.ok(ts.isPropertyAssignment(property), `${file}: non-data property`)
      assert.ok(
        ts.isIdentifier(property.name) || ts.isStringLiteral(property.name) ||
        ts.isNumericLiteral(property.name), `${file}: computed property`
      )
      assertDataLiteral(property.initializer, file)
    }
  } else if (ts.isArrayLiteralExpression(node)) {
    for (const element of node.elements) assertDataLiteral(element, file)
  } else if (ts.isPrefixUnaryExpression(node)) {
    assert.equal(node.operator, ts.SyntaxKind.MinusToken, `${file}: non-data unary operator`)
    assert.ok(ts.isNumericLiteral(node.operand), `${file}: non-numeric unary operand`)
  } else {
    assert.ok(
      ts.isNumericLiteral(node) || ts.isStringLiteral(node) ||
      [ts.SyntaxKind.TrueKeyword, ts.SyntaxKind.FalseKeyword, ts.SyntaxKind.NullKeyword].includes(node.kind),
      `${file}: non-data expression ${ts.SyntaxKind[node.kind]}`
    )
  }
}

test('only generator-owned level data bypasses compilation and every value matches the previous output', async () => {
  const manifest = JSON.parse(readFileSync(new URL('engineering/generated-files.json', root), 'utf8'))
  const levels = manifest.owners.flatMap(owner => owner.outputs)
    .filter(output => output.producer === 'scripts/import-level.py')
    .map(output => output.path).sort()
  assert.ok(levels.length > 0)
  const bypassed = []
  for (const name of readdirSync(new URL('app/', root)).filter(name => name.endsWith('.ts')).sort()) {
    const file = `app/${name}`
    const source = readFileSync(new URL(file, root), 'utf8')
    // Checking the source contract directly avoids compiling unrelated app files
    // in this regression. Actual fixture consumers cover the fallback loader.
    if (!source.startsWith('// Generated by scripts/import-level.py from the supplied ')) continue
    assert.equal(sceneFixtureSource(source), source, file)
    bypassed.push(file)
    const parsed = ts.createSourceFile(file, source, ts.ScriptTarget.ES2022, true)
    assert.deepEqual(parsed.parseDiagnostics, [], file)
    assert.equal(parsed.statements.length, 1, `${file}: extra module statements`)
    const declaration = parsed.statements[0]
    assert.ok(ts.isExportAssignment(declaration) && !declaration.isExportEquals, file)
    assert.ok(ts.isObjectLiteralExpression(declaration.expression), file)
    assertDataLiteral(declaration.expression, file)
    assert.deepEqual(await evaluate(source), await evaluate(previous(source)), file)
  }
  assert.deepEqual(bypassed, levels, 'the bypass covers exactly the generator-owned levels')
})

test('ordinary modules retain TypeScript import elision and property transformation', async () => {
  const source = `
    import { type Missing } from './type-only.ts'
    import { unused } from './unused.ts'
    export default class Fixture {
      declare absent: number
      value: number
      constructor(readonly count: number) {}
    }
  `
  const emitted = sceneFixtureSource(source)
  assert.equal(emitted, previous(source))
  assert.ok(!emitted.includes('type-only.ts'))
  assert.ok(!emitted.includes('unused.ts'))
  const Fixture = await evaluate(emitted)
  const instance = new Fixture(7)
  assert.equal(instance.count, 7)
  assert.equal(Object.hasOwn(instance, 'value'), true)
  assert.equal(Object.hasOwn(instance, 'absent'), false)
})

test('unmarked data and near-matching generator comments keep the compiler fallback', () => {
  for (const source of [
    'export default { value: 1 as number }',
    '// Generated by another importer\nexport default { value: 1 as number }',
    '// Generated by scripts/import-level.py from the supplied levl2016.dat.\nexport default class Fixture { constructor(readonly count: number) {} }',
    '// Generated by scripts/import-level.py from the supplied levl2016.dat.\nconst value: number = 1; export default { value }',
  ]) assert.equal(sceneFixtureSource(source), previous(source))
})
